import { existsSync, writeFileSync } from "node:fs";
import { basename, resolve } from "node:path";
import { localEnvironment, portAvailable, portsForOffset } from "./local-config";

process.chdir(resolve(import.meta.dir, ".."));
const args = process.argv.slice(2);
const configureOnly = args.includes("--configure-only");
const value = (name: string) => args.find((arg) => arg.startsWith(`${name}=`))?.split("=")[1];

if (!existsSync(".env")) {
  // Never adopt legacy volumes or overwrite app secrets implicitly.
  if (["apps/api/.env", "apps/web/.env", "apps/admin/.env"].some(existsSync)) {
    throw new Error(
      "Existing app .env found. Follow docs/local-development.md to preserve its data/configuration before running setup.",
    );
  }
  const slug = basename(process.cwd())
    .toLowerCase()
    .replace(/[^a-z0-9-]/g, "-");
  const project = value("--project") || `${slug}-${crypto.randomUUID().slice(0, 8)}`;
  let offset = Number(value("--offset") ?? 0);
  const explicitOffset = value("--offset") !== undefined;
  while (!(await Promise.all(Object.values(portsForOffset(offset)).map(portAvailable))).every(Boolean)) {
    if (explicitOffset) throw new Error("A requested port is busy. Choose another --offset.");
    offset += 100;
  }
  const env = localEnvironment(
    project,
    offset,
    crypto.randomUUID().replaceAll("-", "") + crypto.randomUUID().replaceAll("-", ""),
  );
  writeFileSync(
    ".env",
    "# Generated by bun run setup; keep this identity to preserve local volumes.\n" +
      Object.entries(env)
        .map(([key, val]) => `${key}=${val}`)
        .join("\n") +
      "\n",
    { mode: 0o600, flag: "wx" },
  );
  console.log(`Created .env for ${project}. Bootstrap admin credentials are in .env.`);
} else if (value("--project") || value("--offset")) {
  throw new Error(
    ".env already exists; setup preserves it. Edit coordinated values explicitly (see docs/local-development.md).",
  );
}

async function run(command: string[]) {
  const child = Bun.spawn(command, { stdout: "inherit", stderr: "inherit", stdin: "inherit" });
  if ((await child.exited) !== 0) throw new Error(`Failed: ${command.join(" ")}`);
}

if (!configureOnly) {
  await run(["bun", "install", "--frozen-lockfile"]);
  await run(["docker", "compose", "up", "-d", "--wait", "--wait-timeout", "120"]);
  // A fresh Bun process loads the newly written root .env before forwarding it to the API.
  await run(["bun", "run", "--filter=api", "db:migrate"]);
  await run(["bun", "run", "--filter=api", "seed:admin"]);
}
console.log("Configuration ready. Run bun run dev. Docker is needed only for the backing services.");
